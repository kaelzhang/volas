#!/usr/bin/env python3
"""Generate `crates/volas-core/src/tz/footers.rs`: every zone's POSIX TZ rule.

The zone tables volas reads (`chrono-tz`) are compiled from the tzdb source and end with
2099: rules in force indefinitely are expanded into explicit transitions only that far.
A TZif file carries those rules on in its footer, a POSIX TZ string (RFC 8536 §3.3),
which is what Python's `zoneinfo` (and every TZif reader) applies past its table. This
script compiles the very tzdb source that `chrono-tz` bundles with `zic` and records
each zone's footer, so both halves of the timeline come from one tzdb release; the
`footers_continue_the_table` test checks every zone's footer against the table over its
last rule-generated years.

Rerun after upgrading `chrono-tz` (the test fails until you do):

    python scripts/gen_tz_footers.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'crates/volas-core/src/tz/footers.rs'
SOURCES = ['africa', 'antarctica', 'asia', 'australasia', 'europe', 'northamerica',
           'southamerica', 'etcetera', 'backward']


def chrono_tz_source() -> Path:
    meta = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--format-version', '1', '--manifest-path', str(ROOT / 'Cargo.toml')]))
    (pkg,) = [p for p in meta['packages'] if p['name'] == 'chrono-tz']
    return Path(pkg['manifest_path']).parent / 'tz'


def footer(tzif: bytes) -> str:
    if not tzif.startswith(b'TZif') or tzif[4:5] < b'2':
        raise SystemExit('expected a TZif version 2+ file')
    return tzif.rstrip(b'\n').rsplit(b'\n', 1)[1].decode('ascii')


def main() -> None:
    src = chrono_tz_source()
    release = re.search(r'^Release (\S+)', (src / 'NEWS').read_text(), re.M).group(1)
    zic = subprocess.check_output(['zic', '--version'], text=True).strip()
    with tempfile.TemporaryDirectory() as out:
        subprocess.run(['zic', '-b', 'fat', '-d', out, *SOURCES], cwd=src, check=True)
        rows = sorted(
            (str(p.relative_to(out)), footer(p.read_bytes()))
            for p in Path(out).rglob('*') if p.is_file()
        )
    lines = [
        f'//! Every zone\'s POSIX TZ rule (its TZif footer), tzdb {release} — the release',
        f'//! `chrono-tz` bundles — compiled by `{zic}`. Generated by',
        '//! `scripts/gen_tz_footers.py`; do not edit.',
        '',
        '/// The tzdb release these rules come from.',
        '#[cfg(test)]',
        f'pub(super) const RELEASE: &str = "{release}";',
        '',
        '/// `(zone name, POSIX TZ rule)`, sorted by name.',
        'pub(super) const FOOTERS: &[(&str, &str)] = &[',
        *(f'    ("{name}", "{rule}"),' for name, rule in rows),
        '];',
        '',
    ]
    OUT.write_text('\n'.join(lines))
    print(f'{len(rows)} zones, tzdb {release} -> {OUT.relative_to(ROOT)}', file=sys.stderr)


if __name__ == '__main__':
    main()
