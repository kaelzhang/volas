//! Named zones past their transition table: the footer rules continue the table, and
//! every lookup — offset, DST component, name, wall clock → instant, period start —
//! follows them (values from Python's `zoneinfo`).

use super::*;

fn at(s: &str) -> i64 {
    crate::datetime::parse_ns(s).unwrap()
}

fn wall(s: &str) -> NaiveDateTime {
    NaiveDateTime::parse_from_str(s, "%Y-%m-%d %H:%M:%S").unwrap()
}

/// Every zone has a footer, every footer parses, and they come from the tzdb release
/// the table was compiled from (rerun `scripts/gen_tz_footers.py` after an upgrade).
#[test]
fn footers_cover_every_zone_of_the_release() {
    assert_eq!(footers::RELEASE, chrono_tz::IANA_TZDB_VERSION);
    assert!(footers::FOOTERS.windows(2).all(|w| w[0].0 < w[1].0), "sorted for the binary search");
    for tz in chrono_tz::TZ_VARIANTS {
        footer_rule(&tz); // panics on a missing or malformed footer
    }
}

/// The table holds explicit transitions through 2099 only, and over its last years —
/// from 2088, after the last one-off transition tzdb predicts (Morocco's Ramadan breaks
/// end in 2087), so generated by the rules in force since — each zone's footer reads
/// exactly what the table does: offset, DST component and name, at every transition and
/// between them.
#[test]
fn footers_continue_the_table() {
    use chrono::Offset;
    use chrono_tz::{OffsetComponents, OffsetName};
    let first = wall("2088-01-01 00:00:00");
    for tz in chrono_tz::TZ_VARIANTS {
        let rule = footer_rule(&tz);
        let check = |utc: NaiveDateTime| {
            let (table, footer) = (tz.offset_from_utc_datetime(&utc), rule.reading_at(utc));
            assert_eq!(table.fix().local_minus_utc(), footer.kind.offset, "{} {utc}", tz.name());
            assert_eq!(table.dst_offset().num_seconds() as i32, footer.dst, "{} {utc}", tz.name());
            let name = table.abbreviation().map_or_else(|| numeric_zone_name(footer.kind.offset), str::to_string);
            assert_eq!(name, footer.kind.abbr, "{} {utc}", tz.name());
        };
        // the table repeats its last span after 2099: no transition past it
        let last = tz.offset_from_utc_datetime(&TABLE_END).fix();
        for d in (0..3 * 365).step_by(7) {
            let utc = TABLE_END + chrono::TimeDelta::days(d);
            assert_eq!(tz.offset_from_utc_datetime(&utc).fix(), last, "{} {utc}", tz.name());
        }
        let mut utc = first;
        let mut prev = tz.offset_from_utc_datetime(&utc).fix();
        while utc < TABLE_END {
            check(utc);
            let next = utc + chrono::TimeDelta::hours(12);
            let cur = tz.offset_from_utc_datetime(&next).fix();
            if cur != prev {
                // the table's transition to the second: the footer agrees either side
                let (mut lo, mut hi) = (utc, next);
                while hi - lo > chrono::TimeDelta::seconds(1) {
                    let mid = lo + chrono::TimeDelta::seconds((hi - lo).num_seconds() / 2);
                    if tz.offset_from_utc_datetime(&mid).fix() == cur { hi = mid } else { lo = mid }
                }
                check(lo);
                check(hi);
            }
            (utc, prev) = (next, cur);
        }
    }
}

#[test]
fn far_future_offsets_dst_and_names_follow_the_rules() {
    let ny = Tz::parse("America/New_York").unwrap();
    assert_eq!(ny.offset_secs_at(at("2115-07-01 12:00:00")), -4 * 3600);
    assert_eq!(ny.zone_name_at(at("2115-07-01 12:00:00")), "EDT");
    assert_eq!(ny.offset_secs_at(at("2115-12-01 12:00:00")), -5 * 3600);
    assert_eq!(ny.civil_parts(at("2115-07-01 12:00:00")), (2115, 7, 1, 8, 0, 0));
    let dublin = Tz::parse("Europe/Dublin").unwrap();
    assert_eq!(dublin.dst_secs_at(at("2150-01-15 12:00:00")), -3600);
    assert_eq!(dublin.zone_name_at(at("2150-01-15 12:00:00")), "GMT");
    let lord_howe = Tz::parse("Australia/Lord_Howe").unwrap();
    assert_eq!(lord_howe.offset_secs_at(at("2150-01-15 12:00:00")), 11 * 3600);
    assert_eq!(lord_howe.dst_secs_at(at("2150-01-15 12:00:00")), 1800);
    // a zone without letters and without DST keeps its numeric name
    let tehran = Tz::parse("Asia/Tehran").unwrap();
    assert_eq!(tehran.zone_name_at(at("2200-01-15 12:00:00")), "+0330");
}

#[test]
fn far_future_wall_clocks_resolve_gaps_and_folds() {
    let ny = Tz::parse("America/New_York").unwrap();
    assert_eq!(ny.localize(wall("2115-07-01 08:00:00")).unwrap(), at("2115-07-01 12:00:00"));
    let gap = ny.localize(wall("2115-03-10 02:30:00")).unwrap_err();
    assert!(gap.to_string().contains("DST gap"), "{gap}");
    let fold = ny.localize(wall("2115-11-03 01:30:00")).unwrap_err();
    assert!(fold.to_string().contains("DST fold"), "{fold}");
    // a period start takes a fold's first occurrence and a gap's end
    assert_eq!(ny.localize_earliest(wall("2115-11-03 01:30:00")).unwrap(), at("2115-11-03 05:30:00"));
    assert_eq!(ny.localize_earliest(wall("2115-03-10 02:30:00")).unwrap(), at("2115-03-10 07:00:00"));
    // Santiago springs forward at midnight: the day starts at 01:00 -03
    let santiago = Tz::parse("America/Santiago").unwrap();
    assert_eq!(santiago.day_start(2150, 9, 6).unwrap(), at("2150-09-06 04:00:00"));
    // the wall clocks straddling the table's end resolve like any other
    assert_eq!(ny.localize(wall("2099-12-31 19:00:00")).unwrap(), at("2100-01-01 00:00:00"));
    // a wall clock past the instant axis — at the end of chrono's calendar too — is out of range
    let end = NaiveDate::MAX.and_hms_opt(23, 0, 0).unwrap();
    assert!(matches!(ny.localize(end), Err(VolasError::Overflow(_))));
    assert!(matches!(ny.localize(wall("2300-07-01 12:00:00")), Err(VolasError::Overflow(_))));
    assert!(matches!(ny.day_start(2300, 3, 10), Err(VolasError::Overflow(_))));
    // no gap has its end past chrono's calendar
    assert_eq!(named_gap_end(&chrono_tz::America::New_York, end), None);
}
